  function load() {
    try {
      var v = localStorage.getItem(STORAGE_KEY);
      if (v && LANGS.some(function (l) { return l.code === v; })) current = v;
    } catch (e) { /* ignore */ }
  }

  function lang() { return current; }

  function langs() { return LANGS.slice(); }

  function setLang(code) {
    if (!LANGS.some(function (l) { return l.code === code; })) code = DEFAULT_LANG;
    current = code;
    try { localStorage.setItem(STORAGE_KEY, code); } catch (e) { /* ignore */ }
    applyStatic(document);
    try {
      window.dispatchEvent(new CustomEvent("tl:langchange", { detail: { lang: code } }));
    } catch (e) { /* ignore */ }
  }

  function pick(dict, key) {
    var table = dict[current];
    if (table && table[key] !== undefined) return table[key];
    var def = dict[DEFAULT_LANG];
    if (def && def[key] !== undefined) return def[key];
    return undefined;
  }

  function t(key, vars) {
    var s = pick(UI, key);
    if (s === undefined) s = key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split("{" + k + "}").join(vars[k]);
      });
    }
    return s;
  }

  function term(key, fallback) {
    var s = pick(TERMS, key);
    return s === undefined ? (fallback !== undefined ? fallback : key) : s;
  }

  function name(kind, id, fallback) {
    return term(kind + "." + id, fallback);
  }

  function applyStatic(root) {
    var r = root || document;
    if (document.documentElement) document.documentElement.lang = current;
    try {
      r.querySelectorAll("[data-i18n]").forEach(function (el) {
        var k = el.getAttribute("data-i18n");
        var s = pick(UI, k);
        if (s !== undefined) el.textContent = s;
      });
      r.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
        var k = el.getAttribute("data-i18n-ph");
        var s = pick(UI, k);
        if (s !== undefined) el.setAttribute("placeholder", s);
      });
      r.querySelectorAll("[data-i18n-title]").forEach(function (el) {
        var k = el.getAttribute("data-i18n-title");
        var s = pick(UI, k);
        if (s !== undefined) el.setAttribute("title", s);
      });
    } catch (e) { /* ignore */ }
  }

  function bindSelect(sel, onChange) {
    if (!sel) return;
    LANGS.forEach(function (l) {
      var o = document.createElement("option");
      o.value = l.code;
      o.textContent = l.native;
      if (l.code === current) o.selected = true;
      sel.appendChild(o);
    });
    sel.addEventListener("change", function () {
      setLang(this.value);
      if (onChange) onChange(this.value);
    });
  }

  function log(key, vars) {
    var s = pick(LOG, key);
    if (s === undefined) return null;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split("{" + k + "}").join(vars[k]);
      });
    }
    return s;
  }

